const VEHICLE_BY_ID = new Map(VEHICLES.map((v) => [v.id, v]));
const SWATCH_BY_ID = new Map(PAINT_SWATCHES.map((s) => [s.id, s]));

/**
 * O(1) vehicle lookup; falls back cleanly to 'sedan' for unknown/empty ids.
 *
 * @param {string} id
 */
export function getVehicleById(id) {
  if (typeof id === 'string' && VEHICLE_BY_ID.has(id)) {
    return VEHICLE_BY_ID.get(id);
  }
  return VEHICLES[0];
}

/**
 * O(1) paint swatch lookup; falls back cleanly to 'red'.
 *
 * @param {string} id
 */
export function getPaintSwatchById(id) {
  if (typeof id === 'string' && SWATCH_BY_ID.has(id)) {
    return SWATCH_BY_ID.get(id);
  }
  return PAINT_SWATCHES[0];
}
